const normalizeKey = (s) => (s || '').replace(/\s+/g, ' ').trim();

function getLanguage() {
  return localStorage.getItem('cybersathi_language') || localStorage.getItem('cybersathi_lang') || 'en';
}

function setLanguage(lang) {
  localStorage.setItem('cybersathi_language', lang);
  localStorage.setItem('cybersathi_lang', lang);
  applyTranslations(lang);

  // Dispatch custom event so dynamic cards re-render
  document.dispatchEvent(new CustomEvent('cybersathi-lang-change', { detail: { lang } }));
}

function translate(text, lang = getLanguage()) {
  const k = normalizeKey(text);
  if (lang === 'en' || !T[k]) return text;
  const idx = lang === 'mr' ? 1 : 0;
  return T[k][idx] || text;
}

function applyTranslations(lang = getLanguage()) {
  document.documentElement.lang = lang;

  // 1. Sync dropdown selects across the page
  document.querySelectorAll('#language, #siteLangSelect, .lang-select').forEach(sel => {
    sel.value = lang;
  });

  // 2. TreeWalker: translate all visible text nodes in the DOM
  if (document.body) {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) {
      textNodes.push(walker.currentNode);
    }

    textNodes.forEach(node => {
      const parent = node.parentElement;
      if (!parent || ['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE'].includes(parent.tagName)) return;
      if (parent.classList.contains('no-translate')) return;

      const original = node.__csOriginal !== undefined ? node.__csOriginal : node.nodeValue;
      if (node.__csOriginal === undefined) {
        node.__csOriginal = original;
      }

      const k = normalizeKey(original);
      if (T[k]) {
        const replacement = lang === 'hi' ? T[k][0] : lang === 'mr' ? T[k][1] : original;
        node.nodeValue = replacement;
      }
    });

    // 3. Translate placeholders and titles
    document.querySelectorAll('input, textarea, select').forEach(el => {
      if (el.placeholder) {
        const origPh = el.__csOriginalPh !== undefined ? el.__csOriginalPh : el.placeholder;
        if (el.__csOriginalPh === undefined) el.__csOriginalPh = origPh;
        const k = normalizeKey(origPh);
        if (T[k]) {
          el.placeholder = lang === 'hi' ? T[k][0] : lang === 'mr' ? T[k][1] : origPh;
        }
      }
    });
  }
}

// Auto-bind on DOM load
document.addEventListener('DOMContentLoaded', () => {
  const current = getLanguage();
  applyTranslations(current);

  document.querySelectorAll('#language, #siteLangSelect, .lang-select').forEach(sel => {
    sel.addEventListener('change', (e) => {
      setLanguage(e.target.value);
    });
  });
});

if (typeof window !== 'undefined') {
  window.getLanguage = getLanguage;
  window.setLanguage = setLanguage;
  window.translate = translate;
  window.applyTranslations = applyTranslations;
  window.CyberSathiI18n = { apply: applyTranslations, setLanguage, getLanguage, translate };
}
